import requests
from bs4 import BeautifulSoup
import csv

url = "https://hands.poker/"

response = requests.get(url, timeout=15)
response.raise_for_status()

soup = BeautifulSoup(response.text, "html.parser")

hands = []

for row in soup.select("table tr"):
    cells = row.find_all(["th", "td"])

    if len(cells) >= 4 and cells[0].get_text(strip=True).isdigit():
        hands.append({
            "Rank": cells[0].get_text(" ", strip=True),
            "Combination": cells[1].get_text(" ", strip=True),
            "Example": cells[2].get_text(" ", strip=True),
            "Odds": cells[3].get_text(" ", strip=True)
        })

if not hands:
    raise ValueError("Таблица не найдена. Проверьте структуру сайта.")

with open("poker_hands.csv", "w", newline="", encoding="utf-8-sig") as file:
    writer = csv.DictWriter(file, fieldnames=hands[0].keys())
    writer.writeheader()
    writer.writerows(hands)

print("Собрано комбинаций:", len(hands))
print("Данные сохранены в poker_hands.csv")